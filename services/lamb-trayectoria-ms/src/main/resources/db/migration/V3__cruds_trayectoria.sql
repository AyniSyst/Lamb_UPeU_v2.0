-- =========================================================================
-- V3: Los 6 CRUDs de trayectoria (los cuadros del documento v3)
-- 1. Estudiante en el plan
-- 2. Avance y requisitos
-- 3. Riesgo academico
-- 4. Tutoria y bienestar
-- 5. Logros y evidencias
-- 6. Cierre y egreso
-- =========================================================================

-- 1) ESTUDIANTE EN EL PLAN
CREATE TABLE IF NOT EXISTS cambios_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    tipo_cambio VARCHAR(30) NOT NULL,
    id_plan_origen BIGINT,
    id_plan_destino BIGINT,
    id_escuela_origen BIGINT,
    id_escuela_destino BIGINT,
    id_sede_origen BIGINT,
    id_sede_destino BIGINT,
    estado_anterior VARCHAR(20) NOT NULL,
    estado_nuevo VARCHAR(20) NOT NULL,
    motivo VARCHAR(500),
    numero_resolucion VARCHAR(50),
    fecha_cambio TIMESTAMP NOT NULL,
    fecha_vigencia DATE,
    PRIMARY KEY (id),
    CONSTRAINT fk_cambio_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_cambio_tipo CHECK (tipo_cambio IN ('CAMBIO_PLAN','TRASLADO_INTERNO','REINCORPORACION','RESERVA','RETIRO','SEPARACION'))
);

-- 2) AVANCE Y REQUISITOS
CREATE TABLE IF NOT EXISTS cumplimientos_requisito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    tipo_requisito VARCHAR(30) NOT NULL,
    id_requisito_externo BIGINT,
    codigo_externo VARCHAR(50),
    descripcion VARCHAR(500),
    cumplido BOOLEAN NOT NULL DEFAULT FALSE,
    valor_cumplimiento VARCHAR(200),
    creditos_reconocidos INTEGER,
    fecha_cumplimiento DATE,
    evidencia_url VARCHAR(500),
    observacion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT fk_cumpl_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_cumpl_tipo CHECK (tipo_requisito IN ('CONVALIDACION','REQUISITO_EGRESO','FORMACION_INTEGRAL','PRACTICAS_PREPROFESIONALES','IDIOMA','INVESTIGACION','EXTRACURRICULAR'))
);

-- 3) RIESGO ACADEMICO
CREATE TABLE IF NOT EXISTS alertas_riesgo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    nivel_riesgo VARCHAR(20) NOT NULL,
    tipo_alerta VARCHAR(30) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    valor_detectado NUMERIC(5,2),
    umbral_regla NUMERIC(5,2),
    numero_repitencia INTEGER,
    codigo_curso VARCHAR(20),
    estado VARCHAR(20) NOT NULL,
    fecha_deteccion TIMESTAMP NOT NULL,
    fecha_cierre TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_alerta_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_alerta_nivel CHECK (nivel_riesgo IN ('BAJO','MEDIO','ALTO','CRITICO')),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ABIERTA','EN_SEGUIMIENTO','CERRADA'))
);

CREATE TABLE IF NOT EXISTS planes_refuerzo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    objetivo VARCHAR(500) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    id_responsable BIGINT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    observacion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT fk_refuerzo_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_refuerzo_estado CHECK (estado IN ('EN_CURSO','COMPLETADO','ANULADO'))
);

CREATE TABLE IF NOT EXISTS cursos_refuerzo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan_refuerzo BIGINT NOT NULL,
    codigo_curso VARCHAR(20) NOT NULL,
    nombre_curso VARCHAR(150),
    numero_repitencia INTEGER NOT NULL DEFAULT 1,
    actividad_asignada VARCHAR(500),
    completado BOOLEAN NOT NULL DEFAULT FALSE,
    observacion VARCHAR(300),
    PRIMARY KEY (id),
    CONSTRAINT fk_cursoref_plan FOREIGN KEY (id_plan_refuerzo) REFERENCES planes_refuerzo (id) ON DELETE CASCADE,
    CONSTRAINT uk_cursoref_plan_curso UNIQUE (id_plan_refuerzo, codigo_curso)
);

-- 4) TUTORIA Y BIENESTAR
CREATE TABLE IF NOT EXISTS tutorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    id_tutor BIGINT NOT NULL,
    programa_tutoria VARCHAR(100),
    periodo VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    PRIMARY KEY (id),
    CONSTRAINT fk_tutoria_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_tutoria_estado CHECK (estado IN ('ACTIVA','FINALIZADA','SUSPENDIDA'))
);

CREATE TABLE IF NOT EXISTS sesiones_tutoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tutoria BIGINT NOT NULL,
    fecha_sesion TIMESTAMP NOT NULL,
    tema VARCHAR(200) NOT NULL,
    observaciones VARCHAR(1000),
    recomendaciones VARCHAR(1000),
    compromiso_estudiante VARCHAR(500),
    derivacion_bienestar VARCHAR(100),
    PRIMARY KEY (id),
    CONSTRAINT fk_sesion_tutoria FOREIGN KEY (id_tutoria) REFERENCES tutorias (id) ON DELETE CASCADE
);

-- 5) LOGROS Y EVIDENCIAS
CREATE TABLE IF NOT EXISTS reconocimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    tipo_reconocimiento VARCHAR(30) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    periodo VARCHAR(20),
    id_competencia BIGINT,
    autoevaluacion VARCHAR(1000),
    evidencia_url VARCHAR(500),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_rec_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_rec_tipo CHECK (tipo_reconocimiento IN ('TERCIO_SUPERIOR','BECA_EXCELENCIA','MENCION','PORTAFOLIO','OTRO'))
);

-- 6) CIERRE Y EGRESO
CREATE TABLE IF NOT EXISTS egresos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    periodo_egreso VARCHAR(20) NOT NULL,
    fecha_egreso DATE NOT NULL,
    creditos_totales INTEGER NOT NULL,
    promedio_final NUMERIC(4,2),
    todos_requisitos_cumplidos BOOLEAN NOT NULL DEFAULT FALSE,
    numero_resolucion VARCHAR(50),
    observacion VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_egreso_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT uk_egreso_trayectoria UNIQUE (id_trayectoria)
);

CREATE TABLE IF NOT EXISTS solicitudes_constancia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    tipo_documento VARCHAR(30) NOT NULL,
    motivo VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    url_documento_generado VARCHAR(500),
    id_responsable BIGINT,
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_entrega TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_const_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT ck_const_tipo CHECK (tipo_documento IN ('CONSTANCIA_ESTUDIOS','CERTIFICADO_ESTUDIOS','CONSTANCIA_EGRESO','RECORD_ACADEMICO','OTRO')),
    CONSTRAINT ck_const_estado CHECK (estado IN ('PENDIENTE','EN_PROCESO','EMITIDA','ENTREGADA','RECHAZADA'))
);

CREATE INDEX IF NOT EXISTS ix_cambio_persona ON cambios_academicos (id_persona);
CREATE INDEX IF NOT EXISTS ix_cumpl_persona ON cumplimientos_requisito (id_persona);
CREATE INDEX IF NOT EXISTS ix_alerta_persona ON alertas_riesgo (id_persona);
CREATE INDEX IF NOT EXISTS ix_tutoria_persona ON tutorias (id_persona);
CREATE INDEX IF NOT EXISTS ix_rec_persona ON reconocimientos (id_persona);
CREATE INDEX IF NOT EXISTS ix_const_persona ON solicitudes_constancia (id_persona);
