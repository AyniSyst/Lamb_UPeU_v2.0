-- Trayectoria de un estudiante: nace con postulante.admitido. Una sola por persona.
CREATE TABLE IF NOT EXISTS trayectorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_programa BIGINT NOT NULL,
    id_postulacion BIGINT NOT NULL,
    periodo_ingreso VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    creditos_aprobados INTEGER NOT NULL DEFAULT 0,
    promedio_ponderado NUMERIC(4,2),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_trayectorias_persona UNIQUE (id_persona)
);

-- Historial derivado de acta.cerrada (no es fuente de verdad: se reconstruye desde evaluacion).
-- uk_historial_persona_seccion es la garantia real de idempotencia ante un acta.cerrada repetido.
CREATE TABLE IF NOT EXISTS historial_cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_seccion BIGINT NOT NULL,
    id_acta BIGINT NOT NULL,
    codigo_curso VARCHAR(20) NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    creditos INTEGER NOT NULL,
    nota_final NUMERIC(4,2) NOT NULL,
    aprobado BOOLEAN NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_historial_persona_seccion UNIQUE (id_persona, id_seccion)
);
