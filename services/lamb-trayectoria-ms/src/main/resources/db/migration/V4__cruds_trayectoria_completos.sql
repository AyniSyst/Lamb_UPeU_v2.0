-- Cuadro 1: datos del plan y de la escuela/sede del estudiante
ALTER TABLE trayectorias ADD COLUMN IF NOT EXISTS id_plan BIGINT;
ALTER TABLE trayectorias ADD COLUMN IF NOT EXISTS creditos_totales_plan INTEGER;
ALTER TABLE trayectorias ADD COLUMN IF NOT EXISTS id_escuela BIGINT;
ALTER TABLE trayectorias ADD COLUMN IF NOT EXISTS id_sede BIGINT;

-- Cuadro 2: no se repite el mismo requisito externo en una trayectoria
CREATE UNIQUE INDEX IF NOT EXISTS uk_cumplimiento_trayectoria_requisito
    ON cumplimientos_requisito (id_trayectoria, tipo_requisito, COALESCE(id_requisito_externo, 0));

-- Cuadro 3: catalogo de niveles, reglas, casos y control de repitencia
CREATE TABLE IF NOT EXISTS niveles_riesgo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_nivel_riesgo_codigo UNIQUE (codigo)
);

CREATE TABLE IF NOT EXISTS reglas_alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    tipo_alerta VARCHAR(30) NOT NULL,
    umbral NUMERIC(5,2) NOT NULL,
    nivel_riesgo VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    descripcion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT ck_regla_nivel CHECK (nivel_riesgo IN ('BAJO','MEDIO','ALTO','CRITICO'))
);

CREATE TABLE IF NOT EXISTS casos_seguimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_alerta BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    id_responsable BIGINT,
    descripcion_intervencion VARCHAR(1000) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_apertura TIMESTAMP NOT NULL,
    fecha_cierre TIMESTAMP,
    resultado VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT fk_caso_alerta FOREIGN KEY (id_alerta) REFERENCES alertas_riesgo (id),
    CONSTRAINT ck_caso_estado CHECK (estado IN ('ABIERTO','EN_PROCESO','CERRADO'))
);

CREATE TABLE IF NOT EXISTS controles_repitencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    codigo_curso VARCHAR(20) NOT NULL,
    numero_repitencia INTEGER NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    observacion VARCHAR(500),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_repitencia_numero CHECK (numero_repitencia BETWEEN 1 AND 4),
    CONSTRAINT ck_repitencia_estado CHECK (estado IN ('REGISTRADA','EN_RIESGO','RETIRADO'))
);

-- Cuadro 4: catalogo de programas de tutoria
CREATE TABLE IF NOT EXISTS programas_tutoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_programa_tutoria_codigo UNIQUE (codigo)
);

ALTER TABLE tutorias ADD COLUMN IF NOT EXISTS id_programa_tutoria BIGINT;
ALTER TABLE tutorias ADD CONSTRAINT fk_tutoria_programa
    FOREIGN KEY (id_programa_tutoria) REFERENCES programas_tutoria (id);

-- Cuadro 6: situacion al cierre e informe para el apoderado
CREATE TABLE IF NOT EXISTS situaciones_cierre (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    estado_academico VARCHAR(20) NOT NULL,
    creditos_aprobados INTEGER NOT NULL DEFAULT 0,
    promedio_periodo NUMERIC(4,2),
    observacion VARCHAR(500),
    fecha_cierre TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_situacion_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id),
    CONSTRAINT uk_situacion_trayectoria_periodo UNIQUE (id_trayectoria, periodo)
);

CREATE TABLE IF NOT EXISTS informes_trayectoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_trayectoria BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    id_apoderado BIGINT,
    resumen VARCHAR(1000) NOT NULL,
    url_documento VARCHAR(500),
    fecha_generacion TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_informe_trayectoria FOREIGN KEY (id_trayectoria) REFERENCES trayectorias (id)
);

-- Indices de consulta
CREATE INDEX IF NOT EXISTS ix_cambio_trayectoria ON cambios_academicos (id_trayectoria);
CREATE INDEX IF NOT EXISTS ix_cumpl_trayectoria ON cumplimientos_requisito (id_trayectoria);
CREATE INDEX IF NOT EXISTS ix_alerta_trayectoria ON alertas_riesgo (id_trayectoria);
CREATE INDEX IF NOT EXISTS ix_caso_alerta ON casos_seguimiento (id_alerta);
CREATE INDEX IF NOT EXISTS ix_repitencia_persona ON controles_repitencia (id_persona);
CREATE INDEX IF NOT EXISTS ix_tutoria_programa ON tutorias (id_programa_tutoria);
CREATE INDEX IF NOT EXISTS ix_situacion_persona ON situaciones_cierre (id_persona);
CREATE INDEX IF NOT EXISTS ix_informe_persona ON informes_trayectoria (id_persona);

