CREATE TABLE IF NOT EXISTS tipos_institucion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS instituciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    razon_social VARCHAR(255) NOT NULL,
    ruc VARCHAR(11) NOT NULL,
    nombre_comercial VARCHAR(150),
    id_tipo_institucion BIGINT NOT NULL REFERENCES tipos_institucion(id),
    direccion VARCHAR(255),
    telefono VARCHAR(20),
    email VARCHAR(100),
    sitio_web VARCHAR(150),
    fecha_fundacion DATE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS autoridades_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    cargo VARCHAR(100) NOT NULL,
    id_institucion BIGINT NOT NULL REFERENCES instituciones(id),
    fecha_inicio DATE,
    fecha_fin DATE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS resoluciones_licenciamiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    numero_resolucion VARCHAR(100) NOT NULL,
    id_institucion BIGINT NOT NULL REFERENCES instituciones(id),
    tipo_licenciamiento VARCHAR(100),
    fecha_emision DATE NOT NULL,
    fecha_vigencia DATE,
    entidad_emisora VARCHAR(150),
    observaciones VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS convenios_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_institucion BIGINT NOT NULL REFERENCES instituciones(id),
    nombre_convenio VARCHAR(150) NOT NULL,
    institucion_socia VARCHAR(150),
    fecha_inicio DATE,
    fecha_fin DATE,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);
