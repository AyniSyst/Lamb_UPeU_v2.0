CREATE TABLE IF NOT EXISTS campus_institucional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    id_institucion BIGINT NOT NULL REFERENCES instituciones(id),
    ciudad VARCHAR(100),
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS tipos_sede (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS sedes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    id_campus BIGINT NOT NULL REFERENCES campus_institucional(id),
    id_tipo_sede BIGINT NOT NULL REFERENCES tipos_sede(id),
    direccion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS direcciones_sede (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_sede BIGINT NOT NULL REFERENCES sedes(id),
    id_ubigeo BIGINT NOT NULL,
    direccion_detalle VARCHAR(255) NOT NULL,
    referencia VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS pabellones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    id_sede BIGINT NOT NULL REFERENCES sedes(id),
    numero_pisos INTEGER,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS ambientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,
    id_pabellon BIGINT REFERENCES pabellones(id),
    id_sede BIGINT NOT NULL REFERENCES sedes(id),
    tipo_ambiente VARCHAR(50),
    capacidad INTEGER,
    PRIMARY KEY (id)
);
