CREATE TABLE IF NOT EXISTS escuelas_profesionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    id_facultad BIGINT NOT NULL REFERENCES facultades(id),
    director VARCHAR(150),
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS departamentos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    id_facultad BIGINT NOT NULL REFERENCES facultades(id),
    jefe_departamento VARCHAR(150),
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS autoridades_facultad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_facultad BIGINT NOT NULL REFERENCES facultades(id),
    cargo VARCHAR(100) NOT NULL,
    fecha_inicio DATE,
    fecha_fin DATE,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cambios_unidad_academica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_facultad BIGINT REFERENCES facultades(id),
    id_escuela BIGINT REFERENCES escuelas_profesionales(id),
    tipo_cambio VARCHAR(100) NOT NULL,
    numero_resolucion VARCHAR(100) NOT NULL,
    fecha_cambio DATE NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS unidades_administrativas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    id_facultad BIGINT REFERENCES facultades(id),
    responsable VARCHAR(150),
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS organigramas_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    id_institucion BIGINT REFERENCES instituciones(id),
    url_documento VARCHAR(255),
    vigente BOOLEAN,
    PRIMARY KEY (id)
);
