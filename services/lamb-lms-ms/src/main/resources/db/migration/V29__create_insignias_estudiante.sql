CREATE TABLE IF NOT EXISTS insignias_estudiante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_insignia BIGINT NOT NULL REFERENCES insignias(id),
    id_estudiante VARCHAR(36) NOT NULL,
    fecha_otorgamiento TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uk_insignias_estudiante_insignia_estudiante UNIQUE (id_insignia, id_estudiante)
);
