CREATE TABLE IF NOT EXISTS avances_contenido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_contenido BIGINT NOT NULL REFERENCES contenidos(id),
    id_estudiante VARCHAR(36) NOT NULL,
    consumido BOOLEAN NOT NULL DEFAULT false,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id),
    CONSTRAINT uk_avances_contenido_contenido_estudiante UNIQUE (id_contenido, id_estudiante)
);
