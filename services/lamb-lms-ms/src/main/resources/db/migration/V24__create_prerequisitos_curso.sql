CREATE TABLE IF NOT EXISTS prerequisitos_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos(id),
    id_curso_prerequisito BIGINT NOT NULL REFERENCES cursos(id),
    PRIMARY KEY (id),
    CONSTRAINT uk_prerequisitos_curso_curso_prerequisito UNIQUE (id_curso, id_curso_prerequisito)
);
