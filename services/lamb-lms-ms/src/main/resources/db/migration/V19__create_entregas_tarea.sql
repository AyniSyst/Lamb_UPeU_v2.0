CREATE TABLE IF NOT EXISTS entregas_tarea (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tarea BIGINT NOT NULL REFERENCES tareas(id),
    id_estudiante VARCHAR(36) NOT NULL,
    url_archivo VARCHAR(500),
    fecha_entrega TIMESTAMP NOT NULL DEFAULT now(),
    nota NUMERIC(5,2),
    PRIMARY KEY (id),
    CONSTRAINT uk_entregas_tarea_tarea_estudiante UNIQUE (id_tarea, id_estudiante)
);
