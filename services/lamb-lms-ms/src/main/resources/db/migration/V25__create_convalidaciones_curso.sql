CREATE TABLE IF NOT EXISTS convalidaciones_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos(id),
    id_estudiante VARCHAR(36) NOT NULL,
    institucion_origen VARCHAR(150) NOT NULL,
    curso_origen VARCHAR(150) NOT NULL,
    fecha_convalidacion DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    PRIMARY KEY (id)
);
