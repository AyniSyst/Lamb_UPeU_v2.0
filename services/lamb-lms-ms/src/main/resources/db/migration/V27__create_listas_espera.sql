CREATE TABLE IF NOT EXISTS listas_espera (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_seccion_curso BIGINT NOT NULL REFERENCES secciones_curso(id),
    id_estudiante VARCHAR(36) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT now(),
    posicion INTEGER NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_listas_espera_seccion_estudiante UNIQUE (id_seccion_curso, id_estudiante)
);
