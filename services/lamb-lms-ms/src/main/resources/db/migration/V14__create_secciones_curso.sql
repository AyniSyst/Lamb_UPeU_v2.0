CREATE TABLE IF NOT EXISTS secciones_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos(id),
    id_docente BIGINT NOT NULL REFERENCES docentes(id),
    id_periodo_academico BIGINT NOT NULL REFERENCES periodos_academicos(id),
    nombre_seccion VARCHAR(10) NOT NULL,
    cupo_maximo INTEGER NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT true,
    PRIMARY KEY (id)
);
