-- Modulo 02 · Curriculo: 47 CRUD del documento CRUD_Admision_a_Trayectoria_UPeU_v3.
-- El catalogo de cursos (CRUD 12) es la fuente del curso; el plan solo lo incluye (PlanCurso).

-- CRUD 1 · Modalidad (presencial, semipresencial, a distancia, virtual): un solo catalogo para programa y curso
CREATE TABLE IF NOT EXISTS modalidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_modalidades_codigo UNIQUE (codigo)
);

-- CRUD 2 · Denominacion del programa
CREATE TABLE IF NOT EXISTS denominaciones_programa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    id_modalidad BIGINT NOT NULL REFERENCES modalidades(id),
    duracion_semestres INTEGER NOT NULL CHECK (duracion_semestres BETWEEN 1 AND 14),
    resolucion VARCHAR(50),
    PRIMARY KEY (id),
    CONSTRAINT uk_denominaciones_programa_id_programa UNIQUE (id_programa)
);

-- CRUD 3 · Grado academico que otorga (bachiller)
CREATE TABLE IF NOT EXISTS grados_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    resolucion VARCHAR(50),
    PRIMARY KEY (id),
    CONSTRAINT uk_grados_academicos_id_programa UNIQUE (id_programa)
);

-- CRUD 4 · Titulo profesional que otorga
CREATE TABLE IF NOT EXISTS titulos_profesionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    resolucion VARCHAR(50),
    PRIMARY KEY (id),
    CONSTRAINT uk_titulos_profesionales_id_programa UNIQUE (id_programa)
);

-- CRUD 6 · Ciclo del plan (I a X)
CREATE TABLE IF NOT EXISTS ciclos_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    numero INTEGER NOT NULL CHECK (numero BETWEEN 1 AND 14),
    nombre VARCHAR(50) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_ciclos_plan_plan_numero UNIQUE (id_plan, numero)
);

-- CRUD 7 · Creditos minimos y maximos por ciclo
CREATE TABLE IF NOT EXISTS creditos_ciclo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_ciclo_plan BIGINT NOT NULL REFERENCES ciclos_plan(id),
    creditos_minimos INTEGER NOT NULL CHECK (creditos_minimos BETWEEN 0 AND 40),
    creditos_maximos INTEGER NOT NULL CHECK (creditos_maximos BETWEEN 1 AND 40),
    PRIMARY KEY (id),
    CONSTRAINT uk_creditos_ciclo_ciclo_plan UNIQUE (id_ciclo_plan),
    CONSTRAINT ck_creditos_ciclo_creditos_maximos CHECK (creditos_maximos IS NULL OR creditos_maximos >= creditos_minimos)
);

-- CRUD 8 · Vigencia del plan por cohorte de ingreso (que cohortes siguen este plan)
CREATE TABLE IF NOT EXISTS vigencias_cohorte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    cohorte_inicio VARCHAR(20) NOT NULL,
    cohorte_fin VARCHAR(20),
    observacion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_vigencias_cohorte_plan_cohorte_inicio UNIQUE (id_plan, cohorte_inicio)
);

-- CRUD 9 · Resolucion de aprobacion del plan
CREATE TABLE IF NOT EXISTS resoluciones_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    numero VARCHAR(50) NOT NULL,
    fecha DATE NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_resoluciones_plan_numero UNIQUE (numero)
);

-- CRUD 10 · Malla curricular (documento adjunto: se guarda la referencia al archivo)
CREATE TABLE IF NOT EXISTS mallas_curriculares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    nombre_archivo VARCHAR(200) NOT NULL,
    url VARCHAR(500) NOT NULL,
    version INTEGER NOT NULL CHECK (version >= 1),
    fecha_carga DATE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_mallas_curriculares_plan_version UNIQUE (id_plan, version)
);

-- CRUD 11 · Departamento academico responsable (jala el id del plan de estudios, CRUD 5)
CREATE TABLE IF NOT EXISTS departamentos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    id_facultad BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT uk_departamentos_academicos_codigo UNIQUE (codigo)
);

-- CRUD 12 · Catalogo de cursos: el curso se define una sola vez aqui; el plan lo incluye como PlanCurso
CREATE TABLE IF NOT EXISTS cursos_catalogo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    creditos INTEGER NOT NULL CHECK (creditos BETWEEN 1 AND 10),
    id_departamento BIGINT REFERENCES departamentos_academicos(id),
    id_modalidad BIGINT REFERENCES modalidades(id),
    PRIMARY KEY (id),
    CONSTRAINT uk_cursos_catalogo_codigo UNIQUE (codigo)
);

-- CRUD 13 · Tipo de curso (obligatorio, requisito, electivo)
CREATE TABLE IF NOT EXISTS tipos_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_tipos_curso_codigo UNIQUE (codigo)
);

-- CRUD 14 · Sumilla del curso
CREATE TABLE IF NOT EXISTS sumillas_curso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos_catalogo(id),
    naturaleza VARCHAR(100) NOT NULL,
    proposito VARCHAR(1000) NOT NULL,
    contenido VARCHAR(2000) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_sumillas_curso_curso UNIQUE (id_curso)
);

-- CRUD 15 · Silabo base del curso (planificacion lo jala para el silabo de cada grupo)
CREATE TABLE IF NOT EXISTS silabos_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos_catalogo(id),
    version VARCHAR(20) NOT NULL,
    competencias VARCHAR(1000),
    metodologia VARCHAR(1000),
    evaluacion VARCHAR(1000),
    bibliografia VARCHAR(2000),
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_silabos_base_curso_version UNIQUE (id_curso, version)
);

-- CRUD 16 · Unidades de aprendizaje del silabo base
CREATE TABLE IF NOT EXISTS unidades_aprendizaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_silabo BIGINT NOT NULL REFERENCES silabos_base(id),
    numero INTEGER NOT NULL CHECK (numero BETWEEN 1 AND 8),
    nombre VARCHAR(200) NOT NULL,
    semana_inicio INTEGER NOT NULL CHECK (semana_inicio BETWEEN 1 AND 20),
    semana_fin INTEGER NOT NULL CHECK (semana_fin BETWEEN 1 AND 20),
    contenidos VARCHAR(2000),
    PRIMARY KEY (id),
    CONSTRAINT uk_unidades_aprendizaje_silabo_numero UNIQUE (id_silabo, numero),
    CONSTRAINT ck_unidades_aprendizaje_semana_fin CHECK (semana_fin IS NULL OR semana_fin >= semana_inicio)
);

-- CRUD 17 · Resultados de aprendizaje del curso
CREATE TABLE IF NOT EXISTS resultados_aprendizaje (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos_catalogo(id),
    codigo VARCHAR(20) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_resultados_aprendizaje_curso_codigo UNIQUE (id_curso, codigo)
);

-- CRUD 18 · Distribucion de horas del curso (teoria, practica, laboratorio)
CREATE TABLE IF NOT EXISTS distribuciones_horas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_curso BIGINT NOT NULL REFERENCES cursos_catalogo(id),
    horas_teoria INTEGER NOT NULL CHECK (horas_teoria BETWEEN 0 AND 10),
    horas_practica INTEGER NOT NULL CHECK (horas_practica BETWEEN 0 AND 10),
    horas_laboratorio INTEGER NOT NULL CHECK (horas_laboratorio BETWEEN 0 AND 10),
    PRIMARY KEY (id),
    CONSTRAINT uk_distribuciones_horas_curso UNIQUE (id_curso)
);

-- CRUD 19 · Requisito de matricula de un curso del plan (curso aprobado, creditos o ciclo minimo)
CREATE TABLE IF NOT EXISTS requisitos_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan_curso BIGINT NOT NULL REFERENCES plan_cursos(id),
    tipo VARCHAR(30) NOT NULL,
    id_curso_requisito BIGINT REFERENCES plan_cursos(id),
    creditos_minimos INTEGER CHECK (creditos_minimos BETWEEN 1 AND 300),
    ciclo_minimo INTEGER CHECK (ciclo_minimo BETWEEN 1 AND 14),
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

-- CRUD 20 · Area curricular (estudios generales, especificos, especialidad)
CREATE TABLE IF NOT EXISTS areas_curriculares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_areas_curriculares_codigo UNIQUE (codigo)
);

-- CRUD 21 · Grupo de electivos (elegir N de M cursos del plan)
CREATE TABLE IF NOT EXISTS grupos_electivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    nombre VARCHAR(150) NOT NULL,
    cantidad_elegir INTEGER NOT NULL CHECK (cantidad_elegir BETWEEN 1 AND 10),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS grupo_electivo_cursos (
    id_grupo_electivo BIGINT NOT NULL REFERENCES grupos_electivos(id) ON DELETE CASCADE,
    id_plan_curso BIGINT NOT NULL REFERENCES plan_cursos(id) ON DELETE CASCADE,
    CONSTRAINT uk_grupo_electivo_cursos UNIQUE (id_grupo_electivo, id_plan_curso)
);

-- CRUD 22 · Eje / linea curricular
CREATE TABLE IF NOT EXISTS ejes_curriculares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT uk_ejes_curriculares_plan_nombre UNIQUE (id_plan, nombre)
);

-- CRUD 23 · Mencion / especialidad
CREATE TABLE IF NOT EXISTS menciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    nombre VARCHAR(150) NOT NULL,
    creditos_requeridos INTEGER NOT NULL CHECK (creditos_requeridos BETWEEN 1 AND 100),
    descripcion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT uk_menciones_plan_nombre UNIQUE (id_plan, nombre)
);

-- CRUD 24 · Linea de investigacion
CREATE TABLE IF NOT EXISTS lineas_investigacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(500),
    activa BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_lineas_investigacion_codigo UNIQUE (codigo)
);

-- CRUD 25 · Curso de investigacion asociado a una linea (relacion linea x curso del plan)
CREATE TABLE IF NOT EXISTS cursos_investigacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_linea BIGINT NOT NULL REFERENCES lineas_investigacion(id),
    id_plan_curso BIGINT NOT NULL REFERENCES plan_cursos(id),
    PRIMARY KEY (id),
    CONSTRAINT uk_cursos_investigacion_linea_plan_curso UNIQUE (id_linea, id_plan_curso)
);

-- CRUD 26 · Actividad de formacion integral (espiritual, cultural, deportiva)
CREATE TABLE IF NOT EXISTS actividades_formacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    creditos INTEGER NOT NULL CHECK (creditos BETWEEN 0 AND 4),
    horas INTEGER NOT NULL CHECK (horas BETWEEN 1 AND 200),
    descripcion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT uk_actividades_formacion_codigo UNIQUE (codigo)
);

-- CRUD 27 · Voluntariado / servicio misionero
CREATE TABLE IF NOT EXISTS voluntariados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    organizacion VARCHAR(150) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    horas_requeridas INTEGER NOT NULL CHECK (horas_requeridas BETWEEN 1 AND 500),
    descripcion VARCHAR(500),
    activo BOOLEAN NOT NULL,
    PRIMARY KEY (id)
);

-- CRUD 28 · Responsabilidad social universitaria (proyeccion social)
CREATE TABLE IF NOT EXISTS proyecciones_sociales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(1000),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    horas INTEGER NOT NULL CHECK (horas BETWEEN 1 AND 1000),
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_proyecciones_sociales_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- CRUD 29 · Perfil de ingreso (lo consulta Admision)
CREATE TABLE IF NOT EXISTS perfiles_ingreso (
