    PRIMARY KEY (id),
    CONSTRAINT uk_requisitos_practicas_plan UNIQUE (id_plan)
);

-- CRUD 36 · Requisito de trabajo de investigacion (bachiller)
CREATE TABLE IF NOT EXISTS requisitos_investigacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
