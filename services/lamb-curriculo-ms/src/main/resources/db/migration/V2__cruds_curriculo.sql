-- CRUD 39 · Equivalencia entre cursos de dos planes
CREATE TABLE IF NOT EXISTS equivalencias_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan_curso_origen BIGINT NOT NULL REFERENCES plan_cursos(id),
    id_plan_curso_destino BIGINT NOT NULL REFERENCES plan_cursos(id),
    tipo VARCHAR(30) NOT NULL,
    observacion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_equivalencias_plan_plan_curso_origen_plan_curso_destino UNIQUE (id_plan_curso_origen, id_plan_curso_destino),
    CONSTRAINT ck_equivalencias_plan_distinto CHECK (id_plan_curso_origen <> id_plan_curso_destino)
);

-- CRUD 40 · Plan de adecuacion / transicion entre un plan y otro
CREATE TABLE IF NOT EXISTS planes_adecuacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan_origen BIGINT NOT NULL REFERENCES planes_estudio(id),
    id_plan_destino BIGINT NOT NULL REFERENCES planes_estudio(id),
    nombre VARCHAR(150) NOT NULL,
    resolucion VARCHAR(50),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    descripcion VARCHAR(1000),
    PRIMARY KEY (id),
    CONSTRAINT uk_planes_adecuacion_plan_origen_plan_destino UNIQUE (id_plan_origen, id_plan_destino),
    CONSTRAINT ck_planes_adecuacion_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT ck_planes_adecuacion_distinto CHECK (id_plan_origen <> id_plan_destino)
);

-- CRUD 42 · Universidad de origen (la consulta Admision para traslados externos)
