    conocimientos VARCHAR(1000),
    habilidades VARCHAR(1000),
    actitudes VARCHAR(1000),
    PRIMARY KEY (id),
    CONSTRAINT uk_perfiles_ingreso_plan UNIQUE (id_plan)
