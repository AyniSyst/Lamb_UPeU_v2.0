-- CRUD 33 · Requisito de egreso (creditos minimos). Trayectoria registra si el estudiante lo cumple
CREATE TABLE IF NOT EXISTS requisitos_egreso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    creditos_obligatorios INTEGER NOT NULL CHECK (creditos_obligatorios BETWEEN 0 AND 400),
    creditos_electivos INTEGER NOT NULL CHECK (creditos_electivos BETWEEN 0 AND 100),
    creditos_totales INTEGER NOT NULL CHECK (creditos_totales BETWEEN 1 AND 400),
    promedio_minimo NUMERIC(4,2),
    PRIMARY KEY (id),
    CONSTRAINT uk_requisitos_egreso_plan UNIQUE (id_plan)
);

-- CRUD 34 · Requisito de idioma extranjero o nativo
CREATE TABLE IF NOT EXISTS requisitos_idioma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    idioma VARCHAR(50) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    nivel VARCHAR(30) NOT NULL,
    modo_acreditacion VARCHAR(200),
    PRIMARY KEY (id),
    CONSTRAINT uk_requisitos_idioma_plan_idioma UNIQUE (id_plan, idioma)
