-- CRUD 38 · Modalidad de titulacion (tesis, suficiencia profesional)
CREATE TABLE IF NOT EXISTS modalidades_titulacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    tipo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(500),
    vigente BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_modalidades_titulacion_plan_tipo UNIQUE (id_plan, tipo)
