-- CRUD 30 · Perfil de egreso
CREATE TABLE IF NOT EXISTS perfiles_egreso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    descripcion VARCHAR(2000) NOT NULL,
