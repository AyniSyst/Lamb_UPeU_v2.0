-- CRUD 47 · Evaluacion curricular periodica
CREATE TABLE IF NOT EXISTS evaluaciones_curriculares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    id_comision BIGINT REFERENCES comisiones_curriculares(id),
    id_periodo BIGINT NOT NULL,
    fecha DATE NOT NULL,
    resultado VARCHAR(30) NOT NULL,
    conclusiones VARCHAR(2000),
    PRIMARY KEY (id)
);

