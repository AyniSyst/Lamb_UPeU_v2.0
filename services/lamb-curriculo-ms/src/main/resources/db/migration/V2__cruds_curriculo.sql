    CONSTRAINT uk_perfiles_egreso_plan UNIQUE (id_plan)
);

-- CRUD 31 · Competencia general (institucional, comun a todos los programas)
CREATE TABLE IF NOT EXISTS competencias_generales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(1000),
    PRIMARY KEY (id),
    CONSTRAINT uk_competencias_generales_codigo UNIQUE (codigo)
