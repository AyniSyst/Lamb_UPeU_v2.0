CREATE TABLE IF NOT EXISTS planes_estudio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_programa BIGINT NOT NULL,
    version VARCHAR(20) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    fecha_publicacion TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uk_plan_programa_version UNIQUE (id_programa, version)
);

-- Solo un plan VIGENTE por programa
CREATE UNIQUE INDEX IF NOT EXISTS uk_plan_vigente_programa
    ON planes_estudio (id_programa)
    WHERE estado = 'VIGENTE';

CREATE TABLE IF NOT EXISTS plan_cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan BIGINT NOT NULL REFERENCES planes_estudio(id),
    codigo_curso VARCHAR(20) NOT NULL,
    nombre_curso VARCHAR(150) NOT NULL,
    ciclo INTEGER NOT NULL CHECK (ciclo BETWEEN 1 AND 14),
    creditos INTEGER NOT NULL CHECK (creditos BETWEEN 1 AND 10),
    tipo VARCHAR(20) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_plan_curso_codigo UNIQUE (id_plan, codigo_curso)
);

CREATE TABLE IF NOT EXISTS prerrequisitos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_plan_curso BIGINT NOT NULL REFERENCES plan_cursos(id) ON DELETE CASCADE,
    id_plan_curso_requisito BIGINT NOT NULL REFERENCES plan_cursos(id),
    PRIMARY KEY (id),
    CONSTRAINT uk_prerrequisito UNIQUE (id_plan_curso, id_plan_curso_requisito),
    CONSTRAINT ck_prerrequisito_distinto CHECK (id_plan_curso <> id_plan_curso_requisito)
);
