CREATE TABLE IF NOT EXISTS reservas_vacante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- JALA ID DE PLANIFICACION: id_seccion lo define y mantiene lamb-planificacion-ms, sin FK local.
    id_seccion BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    fecha_reserva DATE NOT NULL,
    vigencia_hasta DATE,
    estado VARCHAR(20),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS listas_espera_seccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- JALA ID DE PLANIFICACION: id_seccion lo define y mantiene lamb-planificacion-ms, sin FK local.
    id_seccion BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    posicion INTEGER NOT NULL,
    fecha_inscripcion DATE NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS ampliaciones_cupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- JALA ID DE PLANIFICACION: id_seccion lo define y mantiene lamb-planificacion-ms, sin FK local.
    id_seccion BIGINT NOT NULL,
    cupo_adicional INTEGER NOT NULL,
    motivo VARCHAR(255),
    autorizado_por VARCHAR(80),
    PRIMARY KEY (id)
);
