CREATE TABLE IF NOT EXISTS tipos_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS modalidades_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS cronogramas_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    periodo VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS variaciones_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cronograma BIGINT NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS ampliaciones_plazo_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_cronograma BIGINT NOT NULL,
    fecha_ampliada DATE NOT NULL,
    motivo VARCHAR(255),
    autorizado_por VARCHAR(80),
    PRIMARY KEY (id)
);

-- id_requisito_curriculo: JALA ID DE CURRICULO. Referencia externa a lamb-curriculo-ms,
-- sin FK local (ver comentario en RequisitoPorTipoMatricula.java y en el DTO de request).
CREATE TABLE IF NOT EXISTS requisitos_por_tipo_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tipo_matricula BIGINT NOT NULL,
    id_requisito_curriculo BIGINT NOT NULL,
    descripcion VARCHAR(255),
    obligatorio BOOLEAN,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS bloqueos_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    motivo VARCHAR(255),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    activo BOOLEAN,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS compromisos_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_matricula BIGINT NOT NULL,
    monto_comprometido DECIMAL(10,2) NOT NULL,
    fecha_firma DATE NOT NULL,
    documento_url VARCHAR(255),
    PRIMARY KEY (id)
);
