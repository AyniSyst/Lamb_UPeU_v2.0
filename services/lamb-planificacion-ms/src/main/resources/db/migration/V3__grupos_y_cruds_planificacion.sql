CREATE EXTENSION IF NOT EXISTS btree_gist;

-- CRUD 17 · Horario de grupo: detalle de la relacion muchos a muchos Grupo x Ambiente
CREATE TABLE IF NOT EXISTS horarios_grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL REFERENCES grupos(id) ON DELETE CASCADE,
    id_ambiente BIGINT NOT NULL REFERENCES ambientes(id),
    id_periodo BIGINT NOT NULL REFERENCES periodos_academicos(id),
    dia_semana VARCHAR(30) NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    activo BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_horarios_grupo_hora_fin CHECK (hora_fin > hora_inicio),
    -- Ultima red ante una carrera: dos horarios activos del mismo ambiente, periodo y dia no pueden solaparse
    CONSTRAINT ex_horarios_grupo_cruce_ambiente EXCLUDE USING gist (
        id_ambiente WITH =,
        id_periodo WITH =,
        dia_semana WITH =,
        tsrange(DATE '2000-01-01' + hora_inicio, DATE '2000-01-01' + hora_fin) WITH &&
    ) WHERE (activo)
);

CREATE INDEX IF NOT EXISTS ix_horarios_grupo_grupo ON horarios_grupo (id_grupo);

-- CRUD 20 · Asignacion docente: detalle de la relacion muchos a muchos Grupo x Docente
CREATE TABLE IF NOT EXISTS asignaciones_docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL REFERENCES grupos(id) ON DELETE CASCADE,
    id_docente BIGINT NOT NULL,
    rol VARCHAR(30) NOT NULL,
    horas_semanales INTEGER NOT NULL CHECK (horas_semanales BETWEEN 1 AND 40),
    PRIMARY KEY (id),
    CONSTRAINT uk_asignaciones_docente_grupo_docente UNIQUE (id_grupo, id_docente)
);

-- Un solo docente TITULAR por grupo
CREATE UNIQUE INDEX IF NOT EXISTS uk_asignaciones_docente_titular
    ON asignaciones_docente (id_grupo)
    WHERE rol = 'TITULAR';

