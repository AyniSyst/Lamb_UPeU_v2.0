-- CRUD 2 · Tipo de periodo (regular, verano, nivelacion)
CREATE TABLE IF NOT EXISTS tipos_periodo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_tipos_periodo_codigo UNIQUE (codigo)
);

-- CRUD 1 · Periodo academico (2026-I, 2026-II, verano)
CREATE TABLE IF NOT EXISTS periodos_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    id_tipo_periodo BIGINT NOT NULL REFERENCES tipos_periodo(id),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_periodos_academicos_codigo UNIQUE (codigo),
    CONSTRAINT ck_periodos_academicos_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- CRUD 3 · Calendario academico del periodo por sede
CREATE TABLE IF NOT EXISTS calendarios_academicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_periodo BIGINT NOT NULL REFERENCES periodos_academicos(id),
    id_sede BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    resolucion VARCHAR(50),
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_calendarios_academicos_periodo_id_sede UNIQUE (id_periodo, id_sede)
);

-- CRUD 4 · Hito del calendario (inicio, examenes, cierre de notas)
CREATE TABLE IF NOT EXISTS hitos_calendario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_calendario BIGINT NOT NULL REFERENCES calendarios_academicos(id),
    tipo VARCHAR(30) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_hitos_calendario_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- CRUD 5 · Dia no lectivo / feriado
CREATE TABLE IF NOT EXISTS dias_no_lectivos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_calendario BIGINT NOT NULL REFERENCES calendarios_academicos(id),
    fecha DATE NOT NULL,
    motivo VARCHAR(150) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_dias_no_lectivos_calendario_fecha UNIQUE (id_calendario, fecha)
);

-- CRUD 6 · Oferta academica por programa y periodo (el curso se jala de curriculo)
CREATE TABLE IF NOT EXISTS ofertas_academicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_periodo BIGINT NOT NULL REFERENCES periodos_academicos(id),
    -- NULL solo en las ofertas creadas al migrar las secciones antiguas (no tenian programa)
    id_programa BIGINT,
    id_curso BIGINT NOT NULL REFERENCES cursos(id),
    ciclo INTEGER NOT NULL CHECK (ciclo BETWEEN 1 AND 14),
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_ofertas_academicas_periodo_id_programa_curso UNIQUE (id_periodo, id_programa, id_curso)
);

