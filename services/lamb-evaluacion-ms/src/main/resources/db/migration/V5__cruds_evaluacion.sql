-- Modulo 02 · Evaluacion: CRUD del documento CRUD_Admision_a_Trayectoria_UPeU_v3
-- (el 18 se retiro; el 6 Nota ya existia). Las vistas calculadas no tienen tabla.

-- CRUD 1 · Componente de evaluacion (evaluacion de sesiones, evaluacion de producto, examen)
CREATE TABLE IF NOT EXISTS componentes_evaluacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_componentes_evaluacion_codigo UNIQUE (codigo)
);

-- CRUD 2 · Peso de cada componente en la nota final del grupo (la suma por grupo no pasa de 100)
CREATE TABLE IF NOT EXISTS configuraciones_evaluacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    id_componente BIGINT NOT NULL REFERENCES componentes_evaluacion(id),
    peso NUMERIC(5,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_configuraciones_evaluacion_id_grupo_componente UNIQUE (id_grupo, id_componente),
    CONSTRAINT ck_configuraciones_evaluacion_peso CHECK (peso > 0 AND peso <= 100)
);

-- CRUD 3 · Escala de calificacion (vigesimal 0-20, nota minima aprobatoria y regla de redondeo)
CREATE TABLE IF NOT EXISTS escalas_calificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(20) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    nota_minima NUMERIC(4,2) NOT NULL,
    nota_maxima NUMERIC(4,2) NOT NULL,
    nota_aprobatoria NUMERIC(4,2) NOT NULL,
    decimales INTEGER NOT NULL CHECK (decimales BETWEEN 0 AND 2),
    redondeo VARCHAR(30) NOT NULL,
    vigente BOOLEAN NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_escalas_calificacion_codigo UNIQUE (codigo)
);

-- CRUD 4 · Rubrica de un componente de evaluacion
CREATE TABLE IF NOT EXISTS rubricas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_componente BIGINT NOT NULL REFERENCES componentes_evaluacion(id),
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(500),
    PRIMARY KEY (id)
);

-- CRUD 5 · Criterio de rubrica
CREATE TABLE IF NOT EXISTS criterios_rubrica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_rubrica BIGINT NOT NULL REFERENCES rubricas(id),
    orden INTEGER NOT NULL CHECK (orden BETWEEN 1 AND 20),
    descripcion VARCHAR(500) NOT NULL,
    puntaje_maximo NUMERIC(4,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_criterios_rubrica_rubrica_orden UNIQUE (id_rubrica, orden)
);

-- CRUD 7 · Evaluacion programada (fecha de examen)
CREATE TABLE IF NOT EXISTS evaluaciones_programadas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    id_componente BIGINT NOT NULL REFERENCES componentes_evaluacion(id),
    fecha DATE NOT NULL,
    descripcion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_evaluaciones_programadas_id_grupo_componente_fecha UNIQUE (id_grupo, id_componente, fecha)
);

-- CRUD 8 · Calificacion por criterio de rubrica (jala el id del criterio, CRUD 5)
CREATE TABLE IF NOT EXISTS calificaciones_criterio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_criterio BIGINT NOT NULL REFERENCES criterios_rubrica(id),
    id_grupo BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    puntaje NUMERIC(4,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_calificaciones_criterio_criterio_id_grupo_id_persona UNIQUE (id_criterio, id_grupo, id_persona)
);

-- CRUD 9 · Registro de asistencia
CREATE TABLE IF NOT EXISTS registros_asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    id_sesion_clase BIGINT,
    fecha DATE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_registros_asistencia_id_grupo_id_persona_fecha UNIQUE (id_grupo, id_persona, fecha)
);

-- CRUD 10 · Justificacion de inasistencia (al aprobarse la falta pasa a JUSTIFICADA)
CREATE TABLE IF NOT EXISTS justificaciones_inasistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_registro BIGINT NOT NULL REFERENCES registros_asistencia(id),
    motivo VARCHAR(500) NOT NULL,
    documento_url VARCHAR(500),
    id_solicitante BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    observacion_respuesta VARCHAR(255),
    id_respondido_por BIGINT,
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_respuesta TIMESTAMP,
    PRIMARY KEY (id)
);

-- CRUD 11 · Inhabilitacion por inasistencia (30 %): el porcentaje lo calcula el servicio con los registros
CREATE TABLE IF NOT EXISTS inhabilitaciones_inasistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    id_persona BIGINT NOT NULL,
    porcentaje_inasistencia NUMERIC(5,2) NOT NULL,
    fecha DATE NOT NULL,
    observacion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_inhabilitaciones_inasistencia_id_grupo_id_persona UNIQUE (id_grupo, id_persona)
);

-- CRUD 12 · Firma / visado del acta (solo sobre un acta CERRADA)
CREATE TABLE IF NOT EXISTS firmas_acta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_acta BIGINT NOT NULL REFERENCES actas(id),
    id_persona BIGINT NOT NULL,
    rol VARCHAR(30) NOT NULL,
    fecha DATE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_firmas_acta_acta_rol UNIQUE (id_acta, rol)
);

-- CRUD 13 · Acta de rectificacion de la nota final de un estudiante
CREATE TABLE IF NOT EXISTS actas_rectificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_acta BIGINT NOT NULL REFERENCES actas(id),
    id_persona BIGINT NOT NULL,
    nota_anterior NUMERIC(4,2) NOT NULL,
    nota_nueva NUMERIC(4,2) NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    resolucion VARCHAR(50),
    id_solicitante BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    observacion_respuesta VARCHAR(255),
    id_respondido_por BIGINT,
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_respuesta TIMESTAMP,
    PRIMARY KEY (id)
);

-- CRUD 14 · Acta complementaria (examen sustitutorio)
CREATE TABLE IF NOT EXISTS actas_complementarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_acta BIGINT NOT NULL REFERENCES actas(id),
    id_persona BIGINT NOT NULL,
    nota_sustitutorio NUMERIC(4,2) NOT NULL,
    fecha DATE NOT NULL,
    observacion VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_actas_complementarias_acta_id_persona UNIQUE (id_acta, id_persona)
);

-- CRUD 15 · Solicitud de apertura del sistema para notas rezagadas (se responde con el CRUD 16)
CREATE TABLE IF NOT EXISTS solicitudes_apertura_notas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    motivo VARCHAR(500) NOT NULL,
    fecha_inicio_propuesta DATE NOT NULL,
    fecha_fin_propuesta DATE NOT NULL,
    id_solicitante BIGINT NOT NULL,
    estado VARCHAR(30) NOT NULL,
    observacion_respuesta VARCHAR(255),
    id_respondido_por BIGINT,
    fecha_solicitud TIMESTAMP NOT NULL,
    fecha_respuesta TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT ck_solicitudes_apertura_notas_fecha_fin_propuesta CHECK (fecha_fin_propuesta IS NULL OR fecha_fin_propuesta >= fecha_inicio_propuesta)
);

-- CRUD 16 · Respuesta / aprobacion de la solicitud de apertura (quien la aprueba y cuando)
CREATE TABLE IF NOT EXISTS respuestas_solicitud_apertura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud BIGINT NOT NULL REFERENCES solicitudes_apertura_notas(id),
    aprobada BOOLEAN NOT NULL,
    observacion VARCHAR(255),
    id_responsable BIGINT NOT NULL,
    fecha TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_respuestas_solicitud_apertura_solicitud UNIQUE (id_solicitud)
);

-- CRUD 17 · Plazo de apertura habilitado (grupo, docente, fecha de inicio y de cierre)
CREATE TABLE IF NOT EXISTS plazos_apertura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_grupo BIGINT NOT NULL,
    id_docente BIGINT NOT NULL,
    id_solicitud BIGINT REFERENCES solicitudes_apertura_notas(id),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT ck_plazos_apertura_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- CRUD 19 · Encuesta de evaluacion docente
CREATE TABLE IF NOT EXISTS encuestas_docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(150) NOT NULL,
    id_periodo BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT ck_encuestas_docente_fecha_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- CRUD 20 · Pregunta de la evaluacion docente
CREATE TABLE IF NOT EXISTS preguntas_encuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_encuesta BIGINT NOT NULL REFERENCES encuestas_docente(id),
    orden INTEGER NOT NULL CHECK (orden BETWEEN 1 AND 50),
    enunciado VARCHAR(500) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_preguntas_encuesta_encuesta_orden UNIQUE (id_encuesta, orden)
);

-- CRUD 21 · Respuesta de la evaluacion docente (anonima: no guarda al estudiante)
CREATE TABLE IF NOT EXISTS respuestas_encuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_pregunta BIGINT NOT NULL REFERENCES preguntas_encuesta(id),
    id_grupo BIGINT NOT NULL,
    id_docente BIGINT NOT NULL,
    valor_escala INTEGER CHECK (valor_escala BETWEEN 0 AND 5),
    valor_texto VARCHAR(1000),
    PRIMARY KEY (id)
);

