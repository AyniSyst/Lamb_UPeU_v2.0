-- Acta (registro de evaluacion) de una seccion. Una sola por seccion:
-- uk_actas_seccion es la garantia real de idempotencia ante un seccion.abierta repetido.
CREATE TABLE IF NOT EXISTS actas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_seccion BIGINT NOT NULL,
    codigo_curso VARCHAR(20) NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    docente VARCHAR(150),
    estado VARCHAR(20) NOT NULL,
    motivo VARCHAR(255),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_actas_seccion UNIQUE (id_seccion)
);
