CREATE TABLE IF NOT EXISTS series_comprobante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_tipo_comprobante BIGINT NOT NULL REFERENCES tipos_comprobante(id),
    serie VARCHAR(10) NOT NULL,
    correlativo_actual INTEGER NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT true,
    PRIMARY KEY (id),
    CONSTRAINT uk_series_comprobante_tipo_serie UNIQUE (id_tipo_comprobante, serie)
);
