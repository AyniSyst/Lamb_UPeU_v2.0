CREATE TABLE tipos_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE contactos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_tipo_contacto BIGINT NOT NULL,
    valor VARCHAR(150) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE tipos_direccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE direcciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_tipo_direccion BIGINT NOT NULL,
    id_ubigeo BIGINT,
    direccion VARCHAR(255),
    fecha_registro TIMESTAMP
);

CREATE TABLE correos_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    correo VARCHAR(150) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE contactos_emergencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    nombre_contacto VARCHAR(150) NOT NULL,
    telefono VARCHAR(30),
    parentesco VARCHAR(60),
    fecha_registro TIMESTAMP
);

CREATE TABLE verificaciones_contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contacto BIGINT NOT NULL,
    verificado BOOLEAN NOT NULL,
    fecha_verificacion TIMESTAMP
);

CREATE TABLE preferencias_comunicacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    canal VARCHAR(60) NOT NULL,
    horario VARCHAR(60),
    fecha_registro TIMESTAMP
);

CREATE TABLE redes_sociales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    red VARCHAR(60) NOT NULL,
    url VARCHAR(255),
    fecha_registro TIMESTAMP
);
