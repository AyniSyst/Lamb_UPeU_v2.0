CREATE TABLE tipos_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE documentos_persona (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_tipo_documento BIGINT NOT NULL,
    url_archivo VARCHAR(255) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE estados_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE requisitos_documentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_documento BIGINT NOT NULL,
    descripcion VARCHAR(255),
    obligatorio BOOLEAN,
    fecha_registro TIMESTAMP
);

CREATE TABLE historiales_revision_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    comentario VARCHAR(255),
    fecha_revision TIMESTAMP
);

CREATE TABLE vigencias_vencimiento_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    fecha_vigencia_desde DATE,
    fecha_vencimiento DATE,
    fecha_registro TIMESTAMP
);

CREATE TABLE reemplazos_version_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    id_documento_persona_anterior BIGINT,
    motivo VARCHAR(255),
    fecha_registro TIMESTAMP
);

CREATE TABLE observaciones_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    observacion VARCHAR(255) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE firmas_validacion_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_documento_persona BIGINT NOT NULL,
    firmante VARCHAR(150),
    fecha_firma TIMESTAMP
);

CREATE TABLE expedientes_legajo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    codigo VARCHAR(100),
    fecha_registro TIMESTAMP
);
