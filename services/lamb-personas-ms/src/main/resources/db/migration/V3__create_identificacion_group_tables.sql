CREATE TABLE tipos_documento_identidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(255),
    CONSTRAINT uk_tipos_documento_identidad_nombre UNIQUE (nombre)
);

CREATE TABLE documentos_identidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_tipo_documento_identidad BIGINT NOT NULL,
    numero VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE codigos_institucionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    codigo VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE historial_documento_identidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    tipo_cambio VARCHAR(30),
    numero_anterior VARCHAR(20),
    numero_nuevo VARCHAR(20) NOT NULL,
    fecha_cambio TIMESTAMP
);

CREATE TABLE validaciones_identidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    fuente VARCHAR(30) NOT NULL,
    resultado VARCHAR(30) NOT NULL,
    observacion VARCHAR(255),
    fecha_validacion TIMESTAMP
);

CREATE TABLE identificaciones_tributarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    ruc VARCHAR(11) NOT NULL,
    razon_social VARCHAR(150),
    fecha_registro TIMESTAMP
);

CREATE TABLE correcciones_identificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    campo_corregido VARCHAR(50) NOT NULL,
    valor_anterior VARCHAR(100),
    valor_nuevo VARCHAR(100) NOT NULL,
    sustento VARCHAR(255) NOT NULL,
    fecha_correccion TIMESTAMP
);
