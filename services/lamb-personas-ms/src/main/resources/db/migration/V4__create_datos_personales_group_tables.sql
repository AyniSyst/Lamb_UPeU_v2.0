CREATE TABLE sexos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE estados_civiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE nacionalidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE ubigeos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais VARCHAR(60) NOT NULL,
    departamento VARCHAR(60),
    provincia VARCHAR(60),
    distrito VARCHAR(60)
);

CREATE TABLE datos_personales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    fecha_nacimiento DATE,
    lugar_nacimiento VARCHAR(150),
    id_sexo BIGINT,
    id_estado_civil BIGINT,
    id_nacionalidad BIGINT,
    id_ubigeo_nacimiento BIGINT
);

CREATE TABLE discapacidades_condiciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    tipo VARCHAR(100),
    observacion VARCHAR(255),
    fecha_registro TIMESTAMP
);

CREATE TABLE cambios_nombre_apellido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    nombre_anterior VARCHAR(150),
    nombre_nuevo VARCHAR(150) NOT NULL,
    sustento VARCHAR(255) NOT NULL,
    fecha_cambio TIMESTAMP
);

CREATE TABLE consentimientos_datos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    tipo_consentimiento VARCHAR(100) NOT NULL,
    aceptado BOOLEAN NOT NULL,
    fecha_consentimiento TIMESTAMP
);

CREATE TABLE lenguas_idiomas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    idioma VARCHAR(60) NOT NULL,
    nivel VARCHAR(30),
    fecha_registro TIMESTAMP
);

CREATE TABLE autoidentificaciones_etnicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    etnia VARCHAR(100) NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE confesiones_religiosas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    religion VARCHAR(100),
    fecha_registro TIMESTAMP
);

CREATE TABLE colegios_procedencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    nombre_colegio VARCHAR(150) NOT NULL,
    nivel_instruccion VARCHAR(60),
    fecha_registro TIMESTAMP
);

CREATE TABLE datos_socioeconomicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    nivel_socioeconomico VARCHAR(60),
    ingreso_familiar VARCHAR(60),
    fecha_registro TIMESTAMP
);
