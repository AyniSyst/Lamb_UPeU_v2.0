CREATE TABLE tipos_parentesco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE relaciones_familiares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_persona_relacionada BIGINT NOT NULL,
    id_tipo_parentesco BIGINT NOT NULL,
    fecha_registro TIMESTAMP
);

CREATE TABLE responsables_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL,
    id_persona_responsable BIGINT NOT NULL,
    fecha_registro TIMESTAMP
);
