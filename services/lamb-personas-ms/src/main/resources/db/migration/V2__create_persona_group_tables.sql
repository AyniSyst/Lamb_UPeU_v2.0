CREATE TABLE IF NOT EXISTS vinculos_institucion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    tipo_vinculo VARCHAR(20) NOT NULL,
    observacion VARCHAR(255),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS estados_persona (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    estado VARCHAR(20) NOT NULL,
    motivo VARCHAR(255),
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS historial_estados_persona (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30) NOT NULL,
    observacion VARCHAR(255),
    fecha_cambio TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS fusiones_personas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona_origen BIGINT NOT NULL,
    id_persona_destino BIGINT NOT NULL,
    motivo VARCHAR(255),
    fecha_fusion TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS fotografias_persona (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    url_archivo VARCHAR(255) NOT NULL,
    fecha_carga TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS bajas_anonimizacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    motivo VARCHAR(255),
    fecha_aplicacion TIMESTAMP NOT NULL,
    PRIMARY KEY (id)
);
