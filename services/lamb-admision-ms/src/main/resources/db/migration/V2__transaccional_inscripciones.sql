-- =========================================================================
-- V2: Transaccional de admision - Inscripcion (cabecera) + DocumentoPresentado (detalle)
-- Regla de negocio: una inscripcion solo se APRUEBA si trae TODOS los
-- documentos obligatorios que exige la modalidad (ORDINARIA, TRASLADO, etc.)
-- =========================================================================

-- Catalogo: modalidades de admision (ordinaria, traslado externo, convenio, etc.)
CREATE TABLE IF NOT EXISTS modalidades_admision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    vacantes_disponibles INT NOT NULL DEFAULT 0,
    vacantes_ocupadas INT NOT NULL DEFAULT 0,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_modalidad_admision_codigo UNIQUE (codigo),
    CONSTRAINT ck_modalidad_vacantes CHECK (vacantes_ocupadas >= 0 AND vacantes_ocupadas <= vacantes_disponibles)
);

-- Catalogo: tipos de documento (DNI, certificado estudios, acta notas, etc.)
CREATE TABLE IF NOT EXISTS tipos_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(300),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT uk_tipo_documento_codigo UNIQUE (codigo)
);

-- Puente: que tipos de documento son obligatorios por modalidad
CREATE TABLE IF NOT EXISTS modalidad_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_modalidad BIGINT NOT NULL,
    id_tipo_documento BIGINT NOT NULL,
    obligatorio BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (id),
    CONSTRAINT fk_moddoc_modalidad FOREIGN KEY (id_modalidad) REFERENCES modalidades_admision (id),
    CONSTRAINT fk_moddoc_tipo FOREIGN KEY (id_tipo_documento) REFERENCES tipos_documento (id),
    CONSTRAINT uk_moddoc_modalidad_tipo UNIQUE (id_modalidad, id_tipo_documento)
);

-- Cabecera transaccional
CREATE TABLE IF NOT EXISTS inscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_programa BIGINT NOT NULL,
    id_modalidad BIGINT NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    observacion VARCHAR(500),
    fecha_registro TIMESTAMP NOT NULL,
    fecha_aprobacion TIMESTAMP,
    id_aprobado_por BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_inscripcion_modalidad FOREIGN KEY (id_modalidad) REFERENCES modalidades_admision (id),
    CONSTRAINT uk_inscripcion_persona_periodo_programa UNIQUE (id_persona, id_programa, periodo),
    CONSTRAINT ck_inscripcion_estado CHECK (estado IN ('PENDIENTE','APROBADA','RECHAZADA','ANULADA'))
);

-- Detalle transaccional
CREATE TABLE IF NOT EXISTS documentos_presentados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_inscripcion BIGINT NOT NULL,
    id_tipo_documento BIGINT NOT NULL,
    numero_documento VARCHAR(80),
    url_archivo VARCHAR(500),
    observacion VARCHAR(300),
    fecha_entrega TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_docpres_inscripcion FOREIGN KEY (id_inscripcion) REFERENCES inscripciones (id) ON DELETE CASCADE,
    CONSTRAINT fk_docpres_tipo FOREIGN KEY (id_tipo_documento) REFERENCES tipos_documento (id),
    CONSTRAINT uk_docpres_inscripcion_tipo UNIQUE (id_inscripcion, id_tipo_documento)
);

CREATE INDEX IF NOT EXISTS ix_inscripciones_persona ON inscripciones (id_persona);
CREATE INDEX IF NOT EXISTS ix_inscripciones_periodo ON inscripciones (periodo);
CREATE INDEX IF NOT EXISTS ix_docpres_inscripcion ON documentos_presentados (id_inscripcion);

