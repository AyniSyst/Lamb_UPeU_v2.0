-- 1. Convocatoria y oferta
-- 2. Postulante
-- 3. Examen de admision
-- 4. Seguimiento y cierre
-- 5. Examen y calificacion
-- 6. Vacantes e ingreso
-- 7. Casos especiales y excepciones
