-- 1) CONVOCATORIA Y OFERTA
CREATE TABLE IF NOT EXISTS convocatorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    periodo VARCHAR(20) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    fecha_examen DATE,
    estado VARCHAR(20) NOT NULL,
    vacantes_totales INT NOT NULL DEFAULT 0,
    observacion VARCHAR(500),
    PRIMARY KEY (id),
    CONSTRAINT uk_convocatoria_codigo UNIQUE (codigo),
    CONSTRAINT ck_convocatoria_estado CHECK (estado IN ('PLANIFICADA','ABIERTA','CERRADA','ANULADA')),
    CONSTRAINT ck_convocatoria_fechas CHECK (fecha_fin >= fecha_inicio)
);

-- 2) POSTULANTE
CREATE TABLE IF NOT EXISTS postulantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_persona BIGINT NOT NULL,
    id_convocatoria BIGINT NOT NULL,
    id_programa BIGINT NOT NULL,
    id_modalidad BIGINT NOT NULL,
    codigo_postulante VARCHAR(30) NOT NULL,
    colegio_procedencia VARCHAR(200),
    anio_egreso_colegio INT,
    promedio_colegio NUMERIC(4,2),
    telefono_contacto VARCHAR(20),
    correo_contacto VARCHAR(100),
    nombre_apoderado VARCHAR(150),
    telefono_apoderado VARCHAR(20),
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_postulante_convocatoria FOREIGN KEY (id_convocatoria) REFERENCES convocatorias (id),
    CONSTRAINT fk_postulante_modalidad FOREIGN KEY (id_modalidad) REFERENCES modalidades_admision (id),
    CONSTRAINT uk_postulante_codigo UNIQUE (codigo_postulante),
    CONSTRAINT uk_postulante_persona_convocatoria UNIQUE (id_persona, id_convocatoria),
    CONSTRAINT ck_postulante_estado CHECK (estado IN ('REGISTRADO','HABILITADO','EVALUADO','ADMITIDO','NO_ADMITIDO','ANULADO'))
);

-- 3) EXAMEN DE ADMISION
CREATE TABLE IF NOT EXISTS examenes_admision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_convocatoria BIGINT NOT NULL,
    codigo VARCHAR(30) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    fecha_examen TIMESTAMP NOT NULL,
    duracion_minutos INT NOT NULL,
    id_aula BIGINT,
    aforo_maximo INT NOT NULL DEFAULT 0,
    aforo_asignado INT NOT NULL DEFAULT 0,
    estado VARCHAR(20) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_examen_convocatoria FOREIGN KEY (id_convocatoria) REFERENCES convocatorias (id),
    CONSTRAINT uk_examen_codigo UNIQUE (codigo),
    CONSTRAINT ck_examen_estado CHECK (estado IN ('PROGRAMADO','EN_CURSO','FINALIZADO','ANULADO')),
    CONSTRAINT ck_examen_aforo CHECK (aforo_asignado >= 0 AND aforo_asignado <= aforo_maximo)
);

-- 4) SEGUIMIENTO Y CIERRE (contactos al postulante)
CREATE TABLE IF NOT EXISTS seguimientos_postulante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_postulante BIGINT NOT NULL,
    canal VARCHAR(20) NOT NULL,
    medio_captacion VARCHAR(50),
    asunto VARCHAR(200) NOT NULL,
    detalle VARCHAR(1000),
    resultado VARCHAR(20) NOT NULL,
    id_responsable BIGINT,
    fecha_contacto TIMESTAMP NOT NULL,
    proximo_contacto TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_seguimiento_postulante FOREIGN KEY (id_postulante) REFERENCES postulantes (id),
    CONSTRAINT ck_seguimiento_canal CHECK (canal IN ('LLAMADA','WHATSAPP','CORREO','PRESENCIAL','REDES')),
    CONSTRAINT ck_seguimiento_resultado CHECK (resultado IN ('CONTACTADO','NO_CONTESTA','INTERESADO','DESINTERESADO','CERRADO'))
);

-- 5) EXAMEN Y CALIFICACION
CREATE TABLE IF NOT EXISTS calificaciones_examen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_examen BIGINT NOT NULL,
    id_postulante BIGINT NOT NULL,
    puntaje_total NUMERIC(6,2) NOT NULL,
    puntaje_aptitud NUMERIC(6,2),
    puntaje_conocimiento NUMERIC(6,2),
    respuestas_correctas INT,
    respuestas_incorrectas INT,
    respuestas_blanco INT,
    orden_merito INT,
    id_supervisor BIGINT,
    id_encargado BIGINT,
    observacion VARCHAR(500),
    fecha_calificacion TIMESTAMP NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_califica_examen FOREIGN KEY (id_examen) REFERENCES examenes_admision (id),
    CONSTRAINT fk_califica_postulante FOREIGN KEY (id_postulante) REFERENCES postulantes (id),
    CONSTRAINT uk_califica_examen_postulante UNIQUE (id_examen, id_postulante),
    CONSTRAINT ck_califica_puntaje CHECK (puntaje_total >= 0)
);

-- 6) VACANTES E INGRESO (adjudicacion y lista de ingresantes)
CREATE TABLE IF NOT EXISTS adjudicaciones_vacante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_postulante BIGINT NOT NULL,
    id_modalidad BIGINT NOT NULL,
    id_programa BIGINT NOT NULL,
    puntaje_final NUMERIC(6,2) NOT NULL,
    orden_merito INT,
    estado VARCHAR(20) NOT NULL,
    numero_resolucion VARCHAR(50),
    fecha_adjudicacion TIMESTAMP NOT NULL,
    fecha_publicacion TIMESTAMP,
    observacion VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT fk_adjud_postulante FOREIGN KEY (id_postulante) REFERENCES postulantes (id),
    CONSTRAINT fk_adjud_modalidad FOREIGN KEY (id_modalidad) REFERENCES modalidades_admision (id),
    CONSTRAINT uk_adjud_postulante UNIQUE (id_postulante),
    CONSTRAINT ck_adjud_estado CHECK (estado IN ('ADJUDICADA','PUBLICADA','RENUNCIADA','ANULADA'))
);

-- 7) CASOS ESPECIALES Y EXCEPCIONES
CREATE TABLE IF NOT EXISTS casos_especiales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_postulante BIGINT NOT NULL,
    tipo_caso VARCHAR(30) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    requiere_ajuste BOOLEAN NOT NULL DEFAULT FALSE,
    ajuste_otorgado VARCHAR(500),
    nivel_socioeconomico VARCHAR(20),
    id_responsable BIGINT,
    estado VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMP NOT NULL,
    fecha_resolucion TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_caso_postulante FOREIGN KEY (id_postulante) REFERENCES postulantes (id),
    CONSTRAINT ck_caso_tipo CHECK (tipo_caso IN ('FICHA_SOCIOECONOMICA','DISCAPACIDAD','PRORROGA_EXAMEN','CONVALIDACION_TRASLADO','ANULACION_INSCRIPCION','CARGA_MASIVA','OTRO')),
    CONSTRAINT ck_caso_estado CHECK (estado IN ('PENDIENTE','EN_REVISION','APROBADO','RECHAZADO'))
);

CREATE INDEX IF NOT EXISTS ix_postulante_convocatoria ON postulantes (id_convocatoria);
CREATE INDEX IF NOT EXISTS ix_examen_convocatoria ON examenes_admision (id_convocatoria);
CREATE INDEX IF NOT EXISTS ix_seguimiento_postulante ON seguimientos_postulante (id_postulante);
CREATE INDEX IF NOT EXISTS ix_califica_postulante ON calificaciones_examen (id_postulante);
CREATE INDEX IF NOT EXISTS ix_adjud_modalidad ON adjudicaciones_vacante (id_modalidad);
CREATE INDEX IF NOT EXISTS ix_caso_postulante ON casos_especiales (id_postulante);

